import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const outputDir = path.join(rootDir, 'apps/marketing/lib');

// Ensure output directory exists
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

// Fallback seed data (using actual repo statistics)
const SEED_CONTRIBUTORS = [
  {
    login: "kjxcodez",
    id: 104273295, // kjxcodez github user id or default placeholder
    avatar_url: "https://github.com/kjxcodez.png",
    html_url: "https://github.com/kjxcodez",
    contributions: 218
  }
];

async function fetchContributors() {
  const url = 'https://api.github.com/repos/kjxcodez/huntara/contributors';
  console.log(`Querying GitHub API: ${url}`);
  
  try {
    const res = await fetch(url, {
      headers: {
        'User-Agent': 'LeadForge-OS-Builder',
        'Accept': 'application/vnd.github.v3+json'
      },
      signal: AbortSignal.timeout(6000)
    });
    
    if (!res.ok) {
      throw new Error(`HTTP ${res.status}: Failed to fetch contributors`);
    }
    
    const githubContributors = await res.json();
    if (!Array.isArray(githubContributors) || githubContributors.length === 0) {
      console.log('GitHub API returned empty contributors. Using local seed data.');
      return SEED_CONTRIBUTORS;
    }
    
    return githubContributors.map(c => ({
      login: c.login,
      id: c.id,
      avatar_url: c.avatar_url || `https://github.com/${c.login}.png`,
      html_url: c.html_url || `https://github.com/${c.login}`,
      contributions: c.contributions || 0
    }));
  } catch (err) {
    console.warn(`Could not fetch contributors from GitHub (${err.message}). Using fallback seed data.`);
    return SEED_CONTRIBUTORS;
  }
}

async function main() {
  const normalizedContributors = await fetchContributors();
  
  const code = `// Automatically generated by scripts/generate-contributors.mjs
export interface Contributor {
  login: string;
  id: number;
  avatar_url: string;
  html_url: string;
  contributions: number;
}

export const GENERATED_CONTRIBUTORS: Contributor[] = ${JSON.stringify(normalizedContributors, null, 2)};
`;

  fs.writeFileSync(path.join(outputDir, 'generated-contributors.ts'), code, 'utf8');
  console.log(`Generated: Contributors configuration compiled into generated-contributors.ts successfully! 🚀`);
}

main().catch(err => {
  console.error('Fatal error during contributors generation:', err);
  process.exit(1);
});
